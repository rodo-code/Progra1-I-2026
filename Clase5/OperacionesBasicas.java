
public class OperacionesBasicas {

	public static void main(String[] args) {
		// Operaciones con numeros enteros
		int a=73, b=4; // Se pueden crear dos variables o mas en una linea separados por coma
		System.out.println(a+b); // Suma
		System.out.println(a-b); // Resta
		System.out.println(a*b); // Multiplicacion
		System.out.println(a/b); // Division entera
		System.out.println(a%b); // Resto de la division entera
		
		double x=73.00, y=4.00;
		System.out.println(x+y); // Suma
		System.out.println(x-y); // Resta
		System.out.println(x*y); // Multiplicacion
		System.out.println(x/y); // Division
	}

}
