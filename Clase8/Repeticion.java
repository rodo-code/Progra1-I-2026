
public class Repeticion {

	public static void main(String[] args) {
		
		// Inicializamos las repeticiones
		int i=0;
		while (i<100) { // Ponemos la condicion o limite de las repeticiones
			System.out.print(i+" "); // Note que usar print no coloca un fin de linea
			i++; // Incrementa en uno el valor de la variable i
		}
	}

}
